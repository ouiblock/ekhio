/**
 * Get current language from URL param or localStorage, fallback to 'fr'
 */
function getEkhioLang() {
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get('lang');
  if (urlLang && EKHIO_I18N[urlLang]) {
    localStorage.setItem('ekhio_lang', urlLang);
    return urlLang;
  }
  return localStorage.getItem('ekhio_lang') || 'fr';
}

/**
 * Get translation string
 */
function t(key) {
  const lang = getEkhioLang();
  return (EKHIO_I18N[lang] && EKHIO_I18N[lang][key]) || EKHIO_I18N['fr'][key] || key;
}

/**
 * Apply translations to all elements with [data-i18n] attribute
 */
function applyI18n() {
  const lang = getEkhioLang();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (text) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else {
        el.textContent = text;
      }
    }
  });
  // Update <html lang>
  document.documentElement.lang = lang;
  // Update page title
  const titleKey = EKHIO_I18N[lang]?.meta_title;
  if (titleKey) document.title = titleKey;
}

/**
 * Switch language and reload the page with new param
 */
function switchLang(lang) {
  if (!EKHIO_I18N[lang]) return;
  localStorage.setItem('ekhio_lang', lang);
  // Re-apply translations in-place without page reload
  applyI18n();
  // Dispatch custom event so app.html can re-render dynamic content
  window.dispatchEvent(new CustomEvent('ekhio-lang-changed', { detail: { lang } }));
}

// Auto-init on DOMContentLoaded
if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', applyI18n);
}
